"""Cython --embed pipeline with a Visual Studio project.

Flow:
  1. Cython 3.0.11 transpiles entry.py -> entry.c (/* Generated by Cython */).
  2. A .vcxproj + .sln wrapping that C file is generated (toolset v145 for
     Visual Studio 2026, v143 for 2022).
  3. MSBuild (Visual Studio 2026 / 2022) compiles it to EXE.
  4. Visual Studio auto-generates the debug binaries (PDB) via /Zi + /DEBUG.
  5. The stdlib is staged as python314.zip + extension .pyd files next to
     the EXE, so the app boots on a PC with no Python installed.
"""
from __future__ import annotations

import shutil
import struct
import subprocess
import uuid
import zipfile
from pathlib import Path


def prepare_icon(icon_path: str | Path | None, workdir: Path, app_name: str) -> tuple[Path | None, Path | None]:
    """Process .ico or .png into an ICO and an RC file.

    Returns (rc_file, ico_file) or (None, None).
    """
    if not icon_path:
        return None, None

    icon_p = Path(icon_path).resolve()
    if not icon_p.is_file():
        raise FileNotFoundError(f"Icon file not found: {icon_p}")

    workdir.mkdir(parents=True, exist_ok=True)
    ico_dest = workdir / f"{app_name}.ico"
    suffix = icon_p.suffix.lower()

    if suffix == ".ico":
        shutil.copy2(icon_p, ico_dest)
    elif suffix == ".png":
        converted = False
        try:
            from PIL import Image
            img = Image.open(icon_p)
            sizes = [(256, 256), (128, 128), (64, 64), (48, 48), (32, 32), (16, 16)]
            valid = [s for s in sizes if s[0] <= max(img.width, 16)] or [(img.width, img.height)]
            img.save(ico_dest, format="ICO", sizes=valid)
            converted = True
        except ImportError:
            pass

        if not converted:
            png_bytes = icon_p.read_bytes()
            if len(png_bytes) < 24 or png_bytes[:8] != b"\x89PNG\r\n\x1a\n":
                raise ValueError(f"File is not a valid PNG image: {icon_p}")
            width = int.from_bytes(png_bytes[16:20], "big")
            height = int.from_bytes(png_bytes[20:24], "big")
            bw = width if width < 256 else 0
            bh = height if height < 256 else 0
            header = struct.pack("<HHH", 0, 1, 1)
            entry = struct.pack("<BBBBHHII", bw, bh, 0, 0, 1, 32, len(png_bytes), 22)
            ico_dest.write_bytes(header + entry + png_bytes)
        print(f"[cpythonizer] Icon prepared from PNG: {ico_dest.name}")
    else:
        raise ValueError(f"Unsupported icon format: {suffix} (expected .ico or .png)")

    rc_file = workdir / f"{app_name}.rc"
    rc_file.write_text(f'1 ICON "{ico_dest.name}"\n', encoding="utf-8")
    return rc_file, ico_dest


def ensure_cython(python_exe: Path, version: str = "3.0.11") -> None:
    """Install the pinned Cython into the Python 3.14 environment if missing."""
    probe = subprocess.run(
        [str(python_exe), "-m", "cython", "--version"],
        capture_output=True, text=True, timeout=60,
    )
    if probe.returncode == 0 and version in (probe.stdout + probe.stderr):
        print(f"[cpythonizer] Cython {version} OK")
        return
    print(f"[cpythonizer] Installing Cython=={version} ...")
    r = subprocess.run(
        [str(python_exe), "-m", "pip", "install", f"cython=={version}"],
        timeout=300,
    )
    if r.returncode != 0:
        raise RuntimeError("pip install cython failed")


def cythonize_embed(python_exe: Path, entry: Path, workdir: Path, embed: bool = True, release: bool = False) -> Path:
    """Run `cython --embed` on the entry file. Returns the generated .c path."""
    workdir.mkdir(parents=True, exist_ok=True)
    out_c = workdir / (entry.stem + ".c")
    print(f"[cpythonizer] Cython transpiling: {entry} -> {out_c}")
    cmd = [str(python_exe), "-m", "cython"]
    if embed:
        cmd.append("--embed")
    if release:
        cmd.extend([
            "-X", "boundscheck=False",
            "-X", "wraparound=False",
            "-X", "initializedcheck=False",
            "-X", "cdivision=True",
        ])
    cmd.extend(["-3", "--output-file", str(out_c), str(entry)])
    r = subprocess.run(
        cmd,
        capture_output=True, text=True, timeout=300,
    )
    print((r.stdout or "")[-2000:])
    if r.returncode != 0 or not out_c.is_file():
        raise RuntimeError(f"Cython failed:\n{r.stdout}\n{r.stderr}")
    # Sanity: must be genuine Cython output.
    head = out_c.read_text(encoding="utf-8", errors="replace")[:2000]
    if "Generated by Cython" not in head:
        raise RuntimeError("Generated file is not Cython output")
    print(f"[cpythonizer] C generated ({out_c.stat().st_size // 1024} KB)")
    return out_c


def find_msbuild(vs_root: Path) -> Path:
    """Locate MSBuild.exe inside a Visual Studio install root."""
    from .vs import VsInstall, resolve_releases

    # Any release layout works: only the folder name differs per VS version.
    p = VsInstall(resolve_releases("auto")[0], vs_root).msbuild()
    if p is not None:
        return p
    raise FileNotFoundError(f"MSBuild.exe not found under {vs_root}")


